#Небольшой алгоритм, придуманный (по всей видимости) во время приступа бессонницы еще в школе. Создавался на паскале, переложила на питон. Есть идеи по усовершенствованию:)
import random

def main():
    print('Уже идёшь спать?')
    
    # В Pascal random(30) генерирует число от 0 до 29.
    # random.randrange(30) делает то же самое.
    C = random.randrange(30) 
    
    if C == 1:
        print('Неужели ты думаешь, что всё настолько легко? Нееет, самое время ворочаться и страдать от своих же мыслей. На чём зациклишься сегодня?')
        
        # В Python вместо read(A) используется input()
        A = input()
        
        print('Как долго ты будешь ворочаться? Не тебе решать))')
        
        # random(100) генерирует от 0 до 99
        C = random.randrange(100)
        
        while C > 0:
            # В Python print() по умолчанию добавляет пробел между аргументами, 
            # но чтобы точно повторить поведение Pascal (write(A, ' ')), 
            # используем параметр end=' ' и затем выводим пробел вручную или через sep.
            # Проще всего сделать так:
            print(A, end=' ')
            C = C - 1
            
        print(' ') # Переход на новую строку
        print('Просыпайся!')
    else:
        print('Тебе повезло! Эта ночь будет спокойной... Спи сладко')

if __name__ == "__main__":
    main()